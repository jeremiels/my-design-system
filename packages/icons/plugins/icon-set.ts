import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { optimize, type Config, type CustomPlugin } from "svgo";

/**
 * Reads a folder of SVG icons — the base's, or a brand's — and writes them as
 * an icon set (ADR 0005): one optimized module per icon, and an index that
 * loads each module on demand, so a page downloads only the icons it renders.
 *
 * The file name is the icon's name: a brand replaces an icon of the base by
 * writing a file of the same name. The sources are what the designer exports
 * (Figma: fixed dimensions, a fixed color): SVGO normalizes them, and the
 * checks below reject what a page must not run or can't recolor.
 */

/** An icon name: lowercase words joined by hyphens, like component names. */
export const ICON_NAME = /^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/;

/** Names the package's exports already use (`index.js`, `./icon-set`). */
const RESERVED_NAMES = new Set(["index", "icon-set"]);

/** The grid of every icon: icons of a set line up and swap without a shift. */
export const VIEW_BOX = "0 0 24 24";

/** Default budget of an optimized icon, in bytes: more means a failed export (an embedded image, unflattened shapes). */
export const MAX_BYTES = 2048;

/** Elements that run code, load resources or carry styles a page can't override. */
const FORBIDDEN_ELEMENTS = new Set(["script", "foreignObject", "style", "image"]);

/** The first line of every generated file: only those are ever overwritten or deleted. */
const GENERATED = "// Generated by unicorne-icons";

export interface Icon {
  /** For inline use, in a page or a shadow root: no `xmlns`. */
  inline: string;
  /** A standalone `.svg` file, for `<img>`, CSS or native tooling. */
  standalone: string;
}

export interface ReadIconSetOptions {
  /** Budget of an optimized icon (inline), in bytes. Default: `MAX_BYTES`. */
  maxBytes?: number;
}

export interface WriteIconSetOptions {
  /** Folder of the modules: `<name>.js`, `<name>.d.ts`, `index.js`, `index.d.ts`. */
  out: string;
  /** Folder of the standalone `<name>.svg` files. Optional. */
  svgOut?: string;
  /** Name of the set exported by `index.js`. Default: `icons`. */
  exportName?: string;
}

/** Collects what a page must not run, and a grid other than the set's. */
function checks(problems: Set<string>): CustomPlugin {
  return {
    name: "unicorne-icon-checks",
    fn: () => ({
      element: {
        enter(node, parent) {
          if (parent.type === "root") {
            if (node.name !== "svg") {
              problems.add(`the root element is <${node.name}>, not <svg>`);
            } else if (node.attributes.viewBox !== VIEW_BOX) {
              problems.add(
                `viewBox is ${JSON.stringify(node.attributes.viewBox ?? null)}, not "${VIEW_BOX}"`,
              );
            }
          }
          if (FORBIDDEN_ELEMENTS.has(node.name)) {
            problems.add(`<${node.name}> isn't allowed`);
          }
          for (const [attribute, value] of Object.entries(node.attributes)) {
            if (/^on/i.test(attribute)) {
              problems.add(`${attribute} on <${node.name}> isn't allowed`);
            }
            if (/^(?:xlink:)?href$/.test(attribute) && !value.startsWith("#")) {
              problems.add(
                `${attribute}="${value}" on <${node.name}>: only #fragments are allowed`,
              );
            }
          }
        },
      },
    }),
  };
}

function optimization(path: string, inline: boolean): Config {
  return {
    path,
    multipass: true,
    plugins: [
      {
        name: "preset-default",
        params: {
          overrides: {
            // Every color follows the text: `color` styles the icon.
            convertColors: { currentColor: true },
            // The component names the icon (`label`), not the file.
            removeDesc: { removeAny: true },
          },
        },
      },
      // Sized by CSS; the viewBox keeps the proportions.
      "removeDimensions",
      "removeTitle",
      // `href`: SVG 2, supported across the browser matrix.
      "removeXlink",
      // Inline SVG is in the HTML namespace's foreign content: no xmlns needed.
      ...(inline ? (["removeXMLNS"] as const) : []),
    ],
  };
}

/** One icon: checked, then optimized. Throws the list of its problems. */
function readIcon(name: string, path: string, source: string, maxBytes: number): Icon {
  const problems = new Set<string>();
  if (!ICON_NAME.test(name)) {
    problems.add(`"${name}" isn't an icon name: lowercase words joined by hyphens`);
  } else if (RESERVED_NAMES.has(name)) {
    problems.add(`"${name}" is reserved by the package's exports`);
  }
  // The checks run on the source as written, before SVGO rewrites it.
  optimize(source, { path, plugins: [checks(problems)] });
  if (problems.size > 0) {
    throw new Error([...problems].join("; "));
  }
  const icon = {
    inline: optimize(source, optimization(path, true)).data,
    standalone: optimize(source, optimization(path, false)).data,
  };
  const bytes = Buffer.byteLength(icon.inline);
  if (bytes > maxBytes) {
    throw new Error(`${bytes} bytes once optimized, over the budget of ${maxBytes}`);
  }
  return icon;
}

/**
 * Reads every `*.svg` of a folder: icon name → its optimized markup, sorted by
 * name. Throws one error listing every invalid file.
 */
export async function readIconSet(
  dir: string,
  { maxBytes = MAX_BYTES }: ReadIconSetOptions = {},
): Promise<Map<string, Icon>> {
  const files = (await readdir(dir)).filter((file) => file.endsWith(".svg")).sort();
  const icons = new Map<string, Icon>();
  const errors: string[] = [];
  for (const file of files) {
    const path = join(dir, file);
    const name = file.slice(0, -".svg".length);
    try {
      icons.set(name, readIcon(name, path, await readFile(path, "utf8"), maxBytes));
    } catch (error) {
      errors.push(`${path}: ${error instanceof Error ? error.message : String(error)}`);
    }
  }
  if (errors.length > 0) {
    throw new Error(`Invalid icons:\n${errors.map((error) => `- ${error}`).join("\n")}`);
  }
  return icons;
}

/** A JS string literal; SVGO writes attributes in double quotes. */
function quote(text: string): string {
  return `'${text.replace(/\\/g, "\\\\").replace(/'/g, "\\'").replace(/\r?\n/g, "\\n")}'`;
}

function key(name: string): string {
  return /^[a-z][a-z0-9]*$/.test(name) ? name : JSON.stringify(name);
}

/**
 * Empties an output folder of what the generator wrote before (a removed
 * icon must not stay published), and refuses a folder holding anything else.
 */
async function prepare(dir: string, generated: (file: string, content: string) => boolean) {
  await mkdir(dir, { recursive: true });
  const previous: string[] = [];
  const foreign: string[] = [];
  for (const file of await readdir(dir)) {
    const path = join(dir, file);
    const content = await readFile(path, "utf8").catch(() => "");
    (generated(file, content) ? previous : foreign).push(path);
  }
  if (foreign.length > 0) {
    throw new Error(
      `Not written by unicorne-icons: ${foreign.join(", ")}. Use a folder for the generated files only.`,
    );
  }
  await Promise.all(previous.map((path) => rm(path)));
}

/** Writes an icon set read by `readIconSet()`. */
export async function writeIconSet(
  icons: ReadonlyMap<string, Icon>,
  { out, svgOut, exportName = "icons" }: WriteIconSetOptions,
): Promise<void> {
  if (!/^[A-Za-z_$][\w$]*$/.test(exportName)) {
    throw new Error(`exportName ${JSON.stringify(exportName)} isn't a JavaScript identifier.`);
  }
  const names = [...icons.keys()].sort();

  await prepare(out, (_file, content) => content.startsWith(GENERATED));
  for (const name of names) {
    const header = `${GENERATED} from ${name}.svg. Do not edit.\n`;
    await writeFile(
      join(out, `${name}.js`),
      `${header}export default ${quote(icons.get(name)!.inline)};\n`,
    );
    await writeFile(
      join(out, `${name}.d.ts`),
      `${header}/** The SVG markup of the icon. */\ndeclare const svg: string;\nexport default svg;\n`,
    );
  }

  const header = `${GENERATED}. Do not edit.\n`;
  await writeFile(
    join(out, "index.js"),
    `${header}/** Icon name → loader of its module: a page downloads only the icons it renders. */\n` +
      `export const ${exportName} = Object.freeze({\n` +
      names.map((name) => `  ${key(name)}: () => import("./${name}.js"),\n`).join("") +
      `});\n`,
  );
  await writeFile(
    join(out, "index.d.ts"),
    `${header}/** Loads an icon's module: its default export is the icon's SVG markup. */\n` +
      `export type IconLoader = () => Promise<{ default: string }>;\n` +
      `/** An icon: its SVG markup (rendered at once), or a loader of it (rendered once loaded). */\n` +
      `export type IconSource = string | IconLoader;\n` +
      `/** Icon name → icon. */\n` +
      `export type IconSet = Readonly<Record<string, IconSource>>;\n` +
      `/** The names of this set. */\n` +
      `export type IconName = ${names.length > 0 ? names.map((name) => JSON.stringify(name)).join(" | ") : "never"};\n` +
      `/** Icon name → loader of its module: a page downloads only the icons it renders. */\n` +
      `export declare const ${exportName}: Readonly<Record<IconName, IconLoader>>;\n`,
  );

  if (svgOut) {
    // A standalone SVG can't carry the header: the generator owns every
    // `<icon name>.svg` of this folder.
    await prepare(svgOut, (file) => file.endsWith(".svg") && ICON_NAME.test(file.slice(0, -4)));
    for (const name of names) {
      await writeFile(join(svgOut, `${name}.svg`), `${icons.get(name)!.standalone}\n`);
    }
  }
}
