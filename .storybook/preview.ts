import addonA11y from "@storybook/addon-a11y";
import addonDocs from "@storybook/addon-docs";
import * as manifestArgTypes from "@storybook/web-components/entry-preview-argtypes";
import { definePreview, setCustomElementsManifest } from "@storybook/web-components-vite";
import "../src/styles/main.css";
// Opt-in for applications; the docs pages and stories want it.
import "../src/styles/reset.css";
// Registers every component under the default `u-` prefix (ADR 0001, D1).
import "../src/define.ts";
// Generated by `npm run analyze` (ADR 0001, D5): attributes, properties,
// slots, parts, CSS custom properties and events in autodocs and controls.
import manifest from "../custom-elements.json";
// Every component page: autodocs, plus the guidelines of its DSDS document.
import DocumentationTemplate from "./DocumentationTemplate.mdx";

setCustomElementsManifest(manifest);

export default definePreview({
  parameters: {
    options: {
      // Diátaxis order (src/docs/reference/charte-de-redaction.mdx).
      storySort: {
        order: [
          "Documentation",
          ["Premiers pas", "Guides", "Référence", "Explication", "ADR"],
          "Components",
        ],
      },
    },
    controls: {
      matchers: {
        color: /(background|color)$/i,
        date: /Date$/i,
      },
    },
    docs: {
      page: DocumentationTemplate,
      toc: true, // Enables the table of contents
      canvas: {
        sourceState: "shown", // Expands the source code block by default for every story
      },
    },
    a11y: {
      // Any axe violation fails the story's test, in every engine.
      test: "error",
    },
  },

  // definePreview() (CSF Factories) only composes the framework's entry-preview
  // and entry-preview-docs: without entry-preview-argtypes, autodocs and
  // controls ignore the Custom Elements Manifest.
  addons: [addonA11y(), addonDocs(), manifestArgTypes],
});
